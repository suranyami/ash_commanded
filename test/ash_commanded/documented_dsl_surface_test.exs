defmodule AshCommanded.DocumentedDslSurfaceTest do
  @moduledoc """
  Guards the boundary between what this library's documentation claims its DSL accepts and
  what `AshCommanded.Resource.Dsl` actually declares.

  The `command` entity declares `entities: []`. That one fact is why the deleted
  `CollectParameterTransforms` and `CollectParameterValidations` transformers could never
  have worked: `Transformer.get_entities(command, [:transform_params])` can only ever return
  an empty list when the entity declares no nested entities at all. Recording it here as an
  assertion means the next person who wonders why those blocks do not work gets an answer
  from the suite instead of from a review document.
  """

  use ExUnit.Case, async: true

  # Nested block names this repository's documentation has advertised inside a `command` block.
  # Each must either be a real declared entity, or appear nowhere in the scanned files as a
  # declaration. Adding a name here is how a new claim gets policed.
  @nested_block_names [:transform_params, :validate_params, :transaction]

  # Enumerated explicitly, never globbed, so a path typo or a moved file fails loudly instead
  # of finding nothing and passing. `documentation/dsls/` is deliberately absent: those files
  # are generated by `mix spark.cheat_sheets`, not hand-maintained documentation.
  @documentation_files [
    "README.md",
    "documentation/application.md",
    "documentation/commands.md",
    "documentation/context_propagation.md",
    "documentation/error_handling.md",
    "documentation/event_handlers.md",
    "documentation/events.md",
    "documentation/middleware.md",
    "documentation/parameter_handling.md",
    "documentation/projections.md",
    "documentation/routers.md",
    "documentation/snapshotting.md",
    "documentation/transactions.md",
    "cheatsheets/AshCommanded.Resource.Dsl.cheatmd",
    "cheatsheets/AshCqrs.Commanded.Dsl.cheatmd"
  ]

  describe "the declared DSL surface" do
    test "the `command` entity declares no nested entities" do
      commands_section = commands_section()

      assert commands_section,
             "AshCommanded.Resource.Dsl declares no :commands section — the DSL shape changed " <>
               "and this assertion no longer inspects what it claims to"

      command_entity = Enum.find(commands_section.entities, &(&1.name == :command))

      assert command_entity,
             "the :commands section declares no :command entity — the entity was renamed or " <>
               "removed, so this assertion would otherwise pass vacuously"

      assert command_entity.entities == [],
             "the :command entity now declares nested entities " <>
               "#{inspect(Enum.map(command_entity.entities, & &1.name))}; the parameter and " <>
               "transaction blocks previously documented against commands may now be real, " <>
               "and this plan's deletions assumed they could not exist"
    end
  end

  describe "documentation only advertises blocks the extension declares" do
    test "the scan set is non-empty and every enumerated file was actually read" do
      refute @documentation_files == [],
             "the scan set is empty — this guard would compare nothing"

      for path <- @documentation_files do
        assert File.exists?(path),
               "#{path}: enumerated in @documentation_files but missing from disk — " <>
                 "a path typo or a moved file would otherwise find nothing and pass"

        content = File.read!(path)

        assert content != "",
               "#{path}: enumerated but empty — nothing was actually scanned"
      end
    end

    test "the scan set excludes this test's own source and everything under .planning/" do
      own_source = Path.relative_to_cwd(__ENV__.file)

      refute own_source in @documentation_files,
             "the guard's own source must not be in its scan set — it necessarily contains " <>
               "the block names being policed and would exempt itself"

      refute Enum.any?(@documentation_files, &String.starts_with?(&1, ".planning/")),
             ".planning/ must not be in the scan set — planning documents quote the claims " <>
               "being policed"
    end

    test "no scanned documentation file presents an undeclared nested block as a declaration" do
      declared = declared_entity_names()
      contents = Enum.map(@documentation_files, &{&1, File.read!(&1)})

      violations = documentation_violations(contents, declared)

      assert violations == [], format_violations(violations)
    end

    test "the occurrence counter counts occurrences, not files" do
      # A file making two claims, of which one was corrected, must still fail. A guard that
      # counted files containing a match would report 1 for this content and pass.
      content = """
      transform_params do
        map :name, to: :full_name
      end

      transform_params do
        cast :age, :integer
      end
      """

      assert declaration_count(content, :transform_params) == 2
    end

    test "a name the extension declares is not policed — the check inverts when the block lands" do
      # Two-sided by construction: if a later phase really implements `transaction`, the
      # documentation becomes legal without editing this test.
      content = "transaction do\n  enabled? true\nend\n"

      assert documentation_violations([{"synthetic.md", content}], MapSet.new([:transaction])) ==
               []

      assert documentation_violations(
               [{"synthetic.md", content}],
               MapSet.new([:transform_params])
             ) != []
    end
  end

  # Read the shape from the extension rather than from a copy of it, so this test tracks the
  # real declaration. `__sections__/0` returns the `%Spark.Dsl.Section{}` the extension was
  # built from, including every nested section and entity.
  defp commanded_section, do: AshCommanded.Resource.Dsl.__sections__()

  defp commands_section do
    Enum.find(commanded_section().sections, &(&1.name == :commands))
  end

  # Every entity name the extension declares anywhere in its section/entity tree. An entity
  # named `transaction`, `transform_params` or `validate_params` here makes documentation that
  # declares it legal.
  defp declared_entity_names do
    commanded_section()
    |> section_entity_names()
    |> MapSet.new()
  end

  defp section_entity_names(section) do
    Enum.flat_map(section.sections, &section_entity_names/1) ++
      Enum.flat_map(section.entities, &entity_names/1)
  end

  defp entity_names(entity) do
    [entity.name | Enum.flat_map(entity.entities, &entity_names/1)]
  end

  # Scans the whole file for a declaration-shaped line for each policed name. A block
  # declaration is `<name> do` on its own line; prose that merely names the block (even in
  # backticks) is not a declaration. Counting is per occurrence, never per file.
  defp documentation_violations(contents, declared_names) do
    Enum.flat_map(@nested_block_names, fn name ->
      if MapSet.member?(declared_names, name) do
        []
      else
        contents
        |> Enum.map(fn {label, content} -> {label, declaration_count(content, name)} end)
        |> Enum.filter(fn {_label, count} -> count > 0 end)
        |> Enum.map(fn {label, count} -> %{file: label, block: name, count: count} end)
      end
    end)
  end

  defp declaration_count(content, name) do
    content
    |> String.split("\n")
    |> Enum.count(&Regex.match?(declaration_regex(name), &1))
  end

  defp declaration_regex(name) do
    ~r/^\s*#{Regex.escape(Atom.to_string(name))}\s+do\s*$/
  end

  defp format_violations(violations) do
    violations
    |> Enum.map_join("\n", fn violation ->
      "#{violation.file}: presents `#{violation.block}` as a DSL block declaration " <>
        "(#{violation.count} occurrence(s)) but the extension declares no such entity"
    end)
  end
end
