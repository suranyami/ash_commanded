defmodule AshCommanded.Resource.Transformers.GenerateProjectorModules do
  @moduledoc """
  Generates projector modules based on the projections defined in the DSL.

  For each resource with projections, this transformer will generate a projector module
  that subscribes to the events and applies the corresponding projections to update
  the resource state.

  This transformer should run after the projection module transformer.

  ## Example

  Given a resource with several projections, this transformer will generate:

  ```elixir
  defmodule MyApp.Projectors.UserProjector do
    @moduledoc "Event handler that projects events onto the User resource"
    
    use Commanded.Event.Handler,
      application: MyApp.CommandedApplication,
      name: "MyApp.Projectors.UserProjector"
      
    alias MyApp.Projections
    
    def handle(%MyApp.Events.UserRegistered{} = event, _metadata) do
      with {:ok, resource} <- Projections.UserRegistered.apply(event),
           {:ok, _result} <- perform_action(resource, Projections.UserRegistered.action()) do
        :ok
      else
        {:error, reason} -> {:error, reason}
      end
    end
    
    # More handlers for other events...
    
    defp perform_action(changeset, :create), do: Ash.create(changeset)
    defp perform_action(changeset, :update), do: Ash.update(changeset)
    defp perform_action(changeset, :destroy), do: Ash.destroy(changeset)
  end
  ```
  """

  use Spark.Dsl.Transformer
  alias AshCommanded.Resource.Transformers.BaseTransformer
  alias AshCommanded.Resource.Transformers.GenerateProjectionModules
  alias Spark.Dsl.Transformer

  @doc """
  Specifies that this transformer should run after the projection module transformer.
  """
  @impl true
  def after?(GenerateProjectionModules), do: true
  def after?(_), do: false

  @doc """
  Transforms the DSL state to generate projector modules.

  ## Examples

      iex> transform(dsl_state)
      {:ok, updated_dsl_state}
  """
  @impl true
  def transform(dsl_state) do
    resource_module = Transformer.get_persisted(dsl_state, :module)

    projections = Transformer.get_entities(dsl_state, [:commanded, :projections])
    events = Transformer.get_entities(dsl_state, [:commanded, :events])

    # Only proceed if there are projections that should be autogenerated
    case Enum.filter(projections, & &1.autogenerate?) do
      [] ->
        {:ok, dsl_state}

      autogen_projections ->
        # Get the previously generated modules from DSL state
        event_modules = Transformer.get_persisted(dsl_state, :event_modules, [])
        projection_modules = Transformer.get_persisted(dsl_state, :projection_modules, [])

        # Build connections between events and projections
        event_projections = build_event_projection_map(autogen_projections, events)

        # Create the projector module
        app_prefix = BaseTransformer.get_module_prefix(resource_module)
        resource_name = BaseTransformer.get_resource_name(resource_module)

        # Derive the Commanded application module from the domain.
        # Ash persists the domain on the resource DSL state (@persist {:domain, domain}),
        # so we have the domain atom even though the domain module hasn't compiled yet.
        # The naming convention mirrors generate_commanded_application.ex: DomainModule.DomainNameApplication
        domain = Transformer.get_persisted(dsl_state, :domain) || app_prefix
        domain_name = domain |> Module.split() |> List.last()
        commanded_application = Module.concat([domain, "#{domain_name}Application"])

        projector_module = build_projector_module(resource_name, app_prefix)

        # Only the action types a resource's own projections actually declare are emitted as
        # `perform_action/2` clauses below (see `build_action_handlers/1`). Emitting all five
        # possible clauses unconditionally, regardless of which actions this resource uses, is
        # exactly the fat-generated-code pattern FOUND-06/QUAL-02 forbid: every clause the
        # resource's projections never reach is dead code, and `mix compile --warnings-as-errors`
        # (D-26) correctly refuses to pass with a "this clause of defp perform_action/2 is never
        # used" warning for each of them. Fixed at the warning's source (01-07) rather than
        # suppressed.
        actions_used = autogen_projections |> Enum.map(& &1.action) |> Enum.uniq()

        # Create the module AST and define it
        ast =
          build_projector_module_ast(
            resource_module,
            resource_name,
            autogen_projections,
            event_projections,
            event_modules,
            projection_modules,
            commanded_application,
            actions_used
          )

        # Built from the resource's whole `commanded` block, not from one declaration, so
        # there is no entity to attribute it to. Name the resource's own file at line 1
        # rather than guessing at an arbitrary member declaration.
        BaseTransformer.create_module(
          projector_module,
          ast,
          __ENV__,
          BaseTransformer.dsl_location(dsl_state)
        )

        # Store the generated module in DSL state
        updated_dsl_state =
          Transformer.persist(dsl_state, :projector_modules, [
            {resource_module, projector_module}
          ])

        {:ok, updated_dsl_state}
    end
  end

  @doc """
  Builds a map of event names to their corresponding projections.

  ## Examples

      iex> build_event_projection_map(projections, events)
      %{user_registered: [projection1, projection2], email_changed: [projection3]}
  """
  def build_event_projection_map(projections, _events) do
    # We include _events parameter for future enhancements
    # Group projections by the event they respond to
    projections
    |> Enum.group_by(
      fn projection ->
        # Use the explicit event_name or fallback to the projection name
        projection.event_name || projection.name
      end,
      fn projection -> projection end
    )
  end

  @doc """
  Builds the module name for a projector.

  ## Examples

      iex> build_projector_module("User", MyApp)
      MyApp.Projectors.UserProjector
  """
  def build_projector_module(resource_name, app_prefix) do
    Module.concat([app_prefix, "Projectors", "#{resource_name}Projector"])
  end

  @doc """
  Builds the AST (Abstract Syntax Tree) for a projector module.

  ## Examples

      iex> build_projector_module_ast(MyApp.User, "User", projections, event_map, event_modules, projection_modules)
      {:__block__, [], [{:@, [...], [{:moduledoc, [...], [...]}]}, ...]}
  """
  def build_projector_module_ast(
        resource_module,
        resource_name,
        _projections,
        event_projections,
        event_modules,
        projection_modules,
        commanded_application \\ nil,
        actions_used \\ [:create, :update, :destroy, :read]
      ) do
    # Create a more descriptive moduledoc
    moduledoc = "Event handler that projects events onto the #{resource_name} resource"

    # Generate handle function for each event type
    event_handlers =
      event_projections
      |> Enum.map(fn {event_name, event_projections} ->
        build_event_handler(
          event_name,
          event_projections,
          event_modules,
          projection_modules,
          resource_module
        )
      end)

    application_name =
      commanded_application || Module.concat([resource_module, "CommandedApplication"])

    projector_name = "#{resource_module}Projector"

    # Action-specific implementation functions — only for the action types this resource's
    # own projections actually use (see build_action_handlers/1's moduledoc-adjacent comment
    # at the call site in transform/1).
    action_handlers = build_action_handlers(actions_used)

    quote do
      @moduledoc unquote(moduledoc)

      use Commanded.Event.Handler,
        application: unquote(application_name),
        name: unquote(projector_name)
    end
    |> then(fn quoted_core ->
      quote do
        unquote(quoted_core)

        # Aliases for the projection modules
        alias Ash.Changeset
        alias Ash.Resource

        unquote_splicing(event_handlers)

        unquote_splicing(action_handlers)
      end
    end)
  end

  # Build an event handler function for a specific event and its projections
  defp build_event_handler(
         event_name,
         projections,
         event_modules,
         projection_modules,
         resource_module
       ) do
    # Look up the event module for this event
    event_module = event_modules[event_name]

    projection_handlers =
      projections
      |> Enum.map(fn projection ->
        # Look up the projection module for this projection
        projection_module = projection_modules[projection.name]
        action = projection.action

        # For create projections, pass the resource module directly.
        # For update/destroy, look up the existing record by event.id first.
        #
        # `apply/2` (generated by GenerateProjectionModules) returns a bare `%Ash.Changeset{}`,
        # not `{:ok, changeset}` — its own moduledoc says so ("An Ash changeset ready to be
        # applied"). The `with {:ok, changeset} <- ... .apply(...)` shape below previously
        # expected a two-tuple that never arrives, so a `with` match failure (a `WithClauseError`
        # — no `else` clause covers a bare `%Ash.Changeset{}`) fired the moment any projector's
        # `handle/2` ran against a real event. Never caught before Plan 01-06's Task 3, which is
        # the first test in this suite to call a real generated projector's `handle/2` at all.
        if action == :create do
          quote do
            with changeset <- unquote(projection_module).apply(event, unquote(resource_module)),
                 {:ok, result} <- perform_action(changeset, unquote(projection_module).action()) do
              {:ok, result}
            else
              {:error, reason} -> {:error, reason}
            end
          end
        else
          quote do
            with {:ok, record} <- Ash.get(unquote(resource_module), event.id),
                 changeset <- unquote(projection_module).apply(event, record),
                 {:ok, result} <- perform_action(changeset, unquote(projection_module).action()) do
              {:ok, result}
            else
              {:error, reason} -> {:error, reason}
            end
          end
        end
      end)

    # Generate handler function for single projection case vs multiple
    case projection_handlers do
      [single_handler] ->
        # Handle a single projection directly
        quote do
          def handle(%unquote(event_module){} = event, _metadata) do
            unquote(single_handler)
          end
        end

      _multiple_handlers ->
        # Handle multiple projections with a multi_dispatch
        quote do
          def handle(%unquote(event_module){} = event, _metadata) do
            results = [
              unquote_splicing(projection_handlers)
            ]

            # If any projection fails, the whole handler fails
            case Enum.filter(results, fn
                   {:error, _} -> true
                   _ -> false
                 end) do
              [] -> :ok
              [error | _] -> error
            end
          end
        end
    end
  end

  # Build handler functions for different Ash actions — one clause per action type this
  # resource's own projections actually use (`actions_used`), plus a catch-all only when a
  # projection uses an action outside the four Ash standard verbs (a genuinely custom action
  # name). Emitting a clause for an action type no projection reaches produces dead code that
  # `mix compile --warnings-as-errors` correctly refuses to pass ("this clause of defp
  # perform_action/2 is never used") — narrowed here rather than suppressed (see transform/1).
  @standard_action_clauses [
    create:
      quote do
        defp perform_action(changeset, :create), do: Ash.create(changeset)
      end,
    update:
      quote do
        defp perform_action(changeset, :update), do: Ash.update(changeset)
      end,
    destroy:
      quote do
        defp perform_action(changeset, :destroy), do: Ash.destroy(changeset)
      end,
    read:
      quote do
        defp perform_action(changeset, :read), do: Ash.read(changeset)
      end
  ]

  defp build_action_handlers(actions_used) do
    standard_clauses =
      @standard_action_clauses
      |> Enum.filter(fn {action, _ast} -> action in actions_used end)
      |> Enum.map(fn {_action, ast} -> ast end)

    custom_actions = Enum.reject(actions_used, &(&1 in [:create, :update, :destroy, :read]))

    if custom_actions == [] do
      standard_clauses
    else
      standard_clauses ++
        [
          quote do
            defp perform_action(changeset, action) when is_atom(action) do
              # For custom actions, use Ash.run_action
              Ash.run_action(changeset, action)
            end
          end
        ]
    end
  end
end
